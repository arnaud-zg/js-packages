// Renders the shiplane.yml reference page from the schema the package publishes, so the page
// cannot list an adapter, an option or a preset the schema does not.

type Json = Record<string, unknown>;

const isJson = (value: unknown): value is Json =>
  typeof value === "object" && value !== null && !Array.isArray(value);

const at = (value: unknown, ...keys: string[]): unknown =>
  keys.reduce<unknown>((inner, key) => (isJson(inner) ? inner[key] : undefined), value);

const list = (value: unknown): unknown[] => (Array.isArray(value) ? value : []);

const pairs = (value: unknown): [string, unknown][] => (isJson(value) ? Object.entries(value) : []);

const text = (value: unknown) => (typeof value === "string" ? value : "");

const cell = (value: string) => value.replaceAll("|", "\\|").replaceAll("\n", " ");

/** Each entry a slot or a list offers: its name, what it does, the keys its `with` takes. */
const entriesOf = (named: unknown) => {
  const long = list(at(named, "anyOf")).find((branch) => at(branch, "allOf") !== undefined);
  return list(at(long, "allOf")).map((rule) => {
    const name = text(at(rule, "if", "properties", "use", "const"));
    const withSchema = at(rule, "then", "properties", "with");
    const required = new Set(list(at(withSchema, "required")).map(text));
    const keys = pairs(at(withSchema, "properties")).map(
      ([key, schema]) =>
        `\`${key}\`${required.has(key) ? " (required)" : ""}${text(at(schema, "description")) ? `: ${text(at(schema, "description"))}` : ""}`,
    );
    const description = text(
      at(
        list(at(long, "properties", "use", "anyOf")).find((option) => at(option, "const") === name),
        "description",
      ),
    );
    return { name, description, keys };
  });
};

const table = (rows: { name: string; description: string; keys: string[] }[]) => [
  "| Name | What it does | `with` |",
  "| --- | --- | --- |",
  ...rows.map(
    ({ name, description, keys }) =>
      `| \`${name}\` | ${cell(description)} | ${cell(keys.join("; ") || "nothing")} |`,
  ),
];

/** The reference page for shiplane.yml, from the published schema. */
export const configReference = (schema: unknown): string => {
  const properties = at(schema, "properties");
  const flow = at(properties, "flow", "properties");
  const ports = ["sourceControl", "codeHost", "ciPipeline", "versioning"];
  const slotPorts = new Map<string, unknown>();
  const moduleRules = list(
    at(
      list(at(properties, "modules", "items", "anyOf")).find((b) => at(b, "allOf")),
      "allOf",
    ),
  );
  for (const rule of moduleRules) {
    for (const [key, slot] of pairs(at(rule, "then", "properties", "with", "properties"))) {
      if (at(slot, "anyOf") !== undefined) slotPorts.set(key, slot);
    }
  }
  const top = pairs(properties).filter(([key]) => !["flow", "modules", "features"].includes(key));
  return [
    "<!-- Generated by packages/shiplane-integration/src/configReference.ts from `packages/shiplane/shiplane.schema.json`: `SHIPLANE_WRITE_SCHEMA=1 pnpm --filter shiplane-integration test` writes it again. -->",
    "",
    "[🏠 Home](../../README.md) · [📚 Docs](../README.md) ·",
    "[`shiplane`](../../packages/shiplane/README.md) · [🚀 Tutorial](./tutorial.md) ·",
    "[🛠️ How-to](./how-to.md) · [📖 Reference](./reference.md) › **`shiplane.yml`** · [🔌 Plugins](./plugins.md) ·",
    "[💡 Explanation](./explanation.md)",
    "",
    "# 📖 Reference: `shiplane.yml`",
    "",
    "Every key, adapter, module and feature a `shiplane.yml` takes with the first-party plugins installed. A slot is a name, or `use:` the name with `with:` its options. `shiplane schema` adds your own adapters for your editor. How to write one: [How-to: YAML config](./how-to-yaml.md).",
    "",
    "## Flow",
    "",
    ...ports.flatMap((port) => [
      `### \`flow.${port}\``,
      "",
      ...table(entriesOf(at(flow, port))),
      "",
    ]),
    "`flow.approval`: `none` (the default) or `required`.",
    "",
    "## Modules",
    "",
    ...table(entriesOf(at(properties, "modules", "items"))),
    "",
    "## Adapters a module ships with",
    "",
    ...[...slotPorts].flatMap(([key, slot]) => [
      `### \`${key}\``,
      "",
      ...table(entriesOf(slot)),
      "",
    ]),
    "## Features",
    "",
    ...table(entriesOf(at(properties, "features", "items"))),
    "",
    "## Other keys",
    "",
    "| Key | Takes |",
    "| --- | --- |",
    ...top.map(([key, value]) => {
      const names = list(at(value, "anyOf"))
        .flatMap((branch) => list(at(branch, "enum")))
        .concat(list(at(value, "enum")));
      return `| \`${key}\` | ${cell(text(at(value, "description")))}${names.length > 0 ? ` Names: ${names.map((name) => `\`${text(name)}\``).join(", ")}.` : ""} |`;
    }),
    "",
    "## Example",
    "",
    "[`examples/shiplane.yml`](../../packages/shiplane/examples/shiplane.yml) uses five modules and every first-party plugin; `packages/shiplane-integration/src/__tests__/yamlParity.e2e.test.ts` runs it.",
    "",
  ].join("\n");
};
